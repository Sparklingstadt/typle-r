import { test, expect, type Page } from '@playwright/test'
const key = 'typle-r:guest-workspace:v1'
const display = (page: Page, n: number) => page.getByRole('textbox', { name: `表示する単語 ${n}`, exact: true })
const displays = (page: Page) => page.getByRole('textbox', { name: /^表示する単語 \d+$/ })

test('Enter moves between words and adds rows instead of saving', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/create')
  const name = page.getByRole('textbox', { name: '単語リスト名', exact: true })
  await name.fill('Enter list')
  await name.press('Enter')
  await expect(display(page, 1)).toBeFocused()
  await display(page, 1).fill('one')
  await display(page, 1).press('Enter')
  await expect(page).toHaveURL(/\/create$/)
  await expect(display(page, 2)).toBeFocused()
  // An empty last word does not add more rows.
  await display(page, 2).press('Enter')
  await expect(displays(page)).toHaveCount(2)
  await display(page, 2).fill('two')
  // Enter that confirms IME conversion is ignored.
  await display(page, 2).dispatchEvent('keydown', { key: 'Enter', isComposing: true })
  await expect(displays(page)).toHaveCount(2)
  await display(page, 1).press('Enter')
  await expect(display(page, 2)).toBeFocused()
  const input = page.getByRole('textbox', { name: '入力する文字 1', exact: true })
  await input.fill('ichi')
  await input.press('Enter')
  await expect(display(page, 2)).toBeFocused()
  expect(await page.evaluate(k => localStorage.getItem(k), key)).toBeNull()
  await display(page, 2).press('Control+Enter')
  await expect(page).toHaveURL(/\/edit$/)
  const saved = await page.evaluate(k => JSON.parse(localStorage.getItem(k) ?? 'null'), key)
  expect(saved.lists.find((list: { name: string }) => list.name === 'Enter list').words).toEqual([
    { display: 'one', input: 'ichi', annotation: '' },
    { display: 'two', input: 'two', annotation: '' },
  ])
  expect(errors).toEqual([])
})

test('a duplicate name is shown on the name field while the save bar stays visible', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 720 })
  await page.goto('/create')
  await page.getByRole('textbox', { name: '単語リスト名', exact: true }).fill('サンプル：英単語（果物）')
  for (let n = 1; n <= 10; n++) {
    await display(page, n).fill(`word ${n}`)
    await display(page, n).press('Enter')
  }
  await display(page, 11).fill('word 11')
  const save = page.getByRole('button', { name: '保存', exact: true })
  await save.scrollIntoViewIfNeeded()
  await save.click()
  const alert = page.getByRole('alert').filter({ hasText: '同じ名前の単語リストがあります' })
  await expect(alert).toBeInViewport()
  await expect(alert).toHaveCount(1)
  await expect(save).toBeInViewport()
  await expect(page).toHaveURL(/\/create$/)
  // Saving from the top of a long list scrolls the error into view.
  await page.getByRole('textbox', { name: '単語リスト名', exact: true }).press('Control+Enter')
  await expect(alert).toBeInViewport()
})

test('cancel asks before discarding unsaved changes', async ({ page }) => {
  await page.goto('/create')
  await page.getByRole('button', { name: 'キャンセル', exact: true }).click()
  await expect(page).toHaveURL(/\/edit$/)
  await expect(page.getByRole('alertdialog')).toHaveCount(0)

  await page.goto('/create')
  const name = page.getByRole('textbox', { name: '単語リスト名', exact: true })
  await name.fill('Draft')
  await name.fill('')
  await page.getByRole('button', { name: 'キャンセル', exact: true }).click()
  await expect(page).toHaveURL(/\/edit$/)

  await page.goto('/create')
  await name.fill('Draft')
  await display(page, 1).fill('keep me')
  await page.getByRole('button', { name: 'キャンセル', exact: true }).click()
  const dialog = page.getByRole('alertdialog')
  await expect(dialog).toContainText('保存していない変更があります')
  await expect(dialog.getByRole('button', { name: '編集を続ける', exact: true })).toBeFocused()
  await dialog.getByRole('button', { name: '編集を続ける', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page).toHaveURL(/\/create$/)
  await expect(display(page, 1)).toHaveValue('keep me')
  await page.getByRole('button', { name: 'キャンセル', exact: true }).click()
  await dialog.getByRole('button', { name: '破棄して移動', exact: true }).click()
  await expect(page).toHaveURL(/\/edit$/)
  await expect(page.getByRole('button', { name: 'Draft を編集', exact: true })).toHaveCount(0)

  await page.getByRole('button', { name: 'サンプル：英単語（果物） を編集', exact: true }).click()
  await page.getByRole('button', { name: 'キャンセル', exact: true }).click()
  await expect(page.getByRole('alertdialog')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'サンプル：英単語（果物） を編集', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'サンプル：英単語（果物） を編集', exact: true }).click()
  await display(page, 1).fill('changed')
  await page.getByRole('button', { name: 'キャンセル', exact: true }).click()
  await expect(page.getByRole('alertdialog')).toBeVisible()
  await page.getByRole('alertdialog').getByRole('button', { name: '破棄して移動', exact: true }).click()
  await page.getByRole('button', { name: 'サンプル：英単語（果物） を編集', exact: true }).click()
  await expect(display(page, 1)).not.toHaveValue('changed')
})

test('validation errors are shown on the fields and summarized in the save bar', async ({ page }) => {
  await page.goto('/create')
  const name = page.getByRole('textbox', { name: '単語リスト名', exact: true })
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByRole('alert').filter({ hasText: '2件のエラーがあります' })).toBeVisible()
  await expect(name).toBeFocused()
  await expect(name).toHaveAttribute('aria-invalid', 'true')
  await expect(display(page, 1)).toHaveAttribute('aria-invalid', 'true')
  await expect(page.getByText('表示する単語を入力するか、この行を削除してください')).toBeVisible()
  // Errors follow edits after the first attempt.
  await name.fill('Validated')
  await expect(page.getByRole('alert').filter({ hasText: '1件のエラーがあります' })).toBeVisible()
  await page.getByRole('button', { name: '最初のエラーへ移動', exact: true }).click()
  await expect(display(page, 1)).toBeFocused()
  await display(page, 1).fill('ok')
  await expect(page.getByText(/件のエラーがあります/)).toHaveCount(0)
  await expect(display(page, 1)).not.toHaveAttribute('aria-invalid', 'true')
  // An empty row is an error, not silently dropped.
  await page.getByRole('button', { name: '単語を追加', exact: true }).click()
  await expect(display(page, 2)).toBeFocused()
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(display(page, 2)).toBeFocused()
  await expect(page).toHaveURL(/\/create$/)
  await page.getByRole('button', { name: '単語 2 を削除', exact: true }).click()
  await expect(display(page, 1)).toBeFocused()
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page).toHaveURL(/\/edit$/)
})

test('row menu and Alt+Arrow keys reorder and delete words', async ({ page }) => {
  await page.goto('/create')
  for (const [n, word] of ['a', 'b', 'c'].entries()) {
    await display(page, n + 1).fill(word)
    await display(page, n + 1).press('Enter')
  }
  await page.getByRole('button', { name: '単語 4 を削除', exact: true }).click()
  await expect(displays(page)).toHaveCount(3)
  const values = async () => Promise.all([1, 2, 3].map(n => display(page, n).inputValue()))
  await page.getByRole('button', { name: '単語 3 の操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '先頭へ移動', exact: true }).click()
  expect(await values()).toEqual(['c', 'a', 'b'])
  await page.getByRole('button', { name: '単語 1 の操作', exact: true }).click()
  await expect(page.getByRole('menuitem', { name: '上へ移動', exact: true })).toBeDisabled()
  await page.getByRole('menuitem', { name: '末尾へ移動', exact: true }).click()
  expect(await values()).toEqual(['a', 'b', 'c'])
  await display(page, 2).focus()
  await page.keyboard.press('Alt+ArrowUp')
  expect(await values()).toEqual(['b', 'a', 'c'])
  // Focus stays on the moved word.
  await expect(display(page, 1)).toBeFocused()
  await page.keyboard.press('Alt+ArrowDown')
  await page.keyboard.press('Alt+ArrowDown')
  expect(await values()).toEqual(['a', 'c', 'b'])
  await page.getByRole('button', { name: '単語 2 の操作', exact: true }).click()
  await page.getByRole('menuitem', { name: 'この単語を削除', exact: true }).click()
  expect(await Promise.all([1, 2].map(n => display(page, n).inputValue()))).toEqual(['a', 'b'])
  await expect(displays(page)).toHaveCount(2)
})

test('CSV import can append to or replace the entered words', async ({ page }) => {
  await page.goto('/create')
  await page.getByRole('textbox', { name: '単語リスト名', exact: true }).fill('Mixed')
  await display(page, 1).fill('keep')
  await display(page, 1).press('Enter')
  const csv = { name: 'more.csv', mimeType: 'text/csv', buffer: Buffer.from('display,input\nx,ex\ny,why') }
  await page.getByRole('button', { name: 'CSV・TSVを読み込む', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'CSV・TSVから読み込む' })
  await dialog.getByLabel('CSV・TSVファイルを選択', { exact: true }).setInputFiles(csv)
  // The empty second row is not counted and is dropped when appending.
  await expect(dialog.getByText('入力済みの1語のあとに2語を追加します。')).toBeVisible()
  await dialog.getByRole('button', { name: '2語を追加', exact: true }).click()
  expect(await Promise.all([1, 2, 3].map(n => display(page, n).inputValue()))).toEqual(['keep', 'x', 'y'])
  await expect(displays(page)).toHaveCount(3)
  await page.getByRole('button', { name: 'CSV・TSVを読み込む', exact: true }).click()
  await dialog.getByLabel('CSV・TSVファイルを選択', { exact: true }).setInputFiles(csv)
  await dialog.getByRole('radio', { name: /今の単語を置き換える/ }).check()
  await dialog.getByRole('button', { name: '2語で置き換える', exact: true }).click()
  expect(await Promise.all([1, 2].map(n => display(page, n).inputValue()))).toEqual(['x', 'y'])
  await expect(displays(page)).toHaveCount(2)
  await expect(page.getByRole('textbox', { name: '単語リスト名', exact: true })).toHaveValue('Mixed')
})
